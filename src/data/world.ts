export function mapWorld(complete: boolean, latest: DestinationEnvironment | undefined): WorldState {
  if (complete) {
    return {
      timeOfDay: 'twilight',
      weather: 'goldenCalm',
      windIntensity: 0.12,
      fogIntensity: 0.08,
      oceanIntensity: 'calm',
      lightingMood: 'twilightMap',
      particleDensity: 0.35,
      cameraMood: 'still',
      audioMood: 'completedTwilight',
      particleMode: 'stars',
    }
  }
  return {
    timeOfDay: latest?.timeOfDay ?? 'earlyMorning',
    weather: latest?.weather ?? 'mist',
    windIntensity: latest?.windIntensity ?? 0.25,
    fogIntensity: 0.28,
    oceanIntensity: 'normal',
    lightingMood: latest?.lightingMood ?? 'coolSun',
    particleDensity: 0.4,
    cameraMood: 'still',
    audioMood: 'mapDay',
    particleMode: 'dust',
  }
}

export function transitionFromLegacy(type: TransitionType): TransitionKind {
  if (type === 'fog') return 'fogWipe'
  if (type === 'water') return 'oceanDive'
  if (type === 'light') return 'lightFlash'
  if (type === 'glitch') return 'oracleGlitch'
  if (type === 'sun') return 'sunFlare'
  return 'cloudPass'
}

